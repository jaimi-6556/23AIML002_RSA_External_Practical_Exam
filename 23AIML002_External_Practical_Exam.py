print("RANK  FEATURE              MEAN|SHAP|")
print("-"*39)
for rank, (idx, row) in enumerate(importance_df.head(5).iterrows(), 1):
    print(f" {rank:<4} {row['FEATURE']:<20} {row['MEAN|SHAP|']:.3f}")
print("-"*39)
print("Plot saved : shap_summary.png\n")

"""## TASK 4 & 5: Local Explanations with SHAP & LIME"""

# Let's find a rejected applicant (where predicted probability of class 1 > 0.5)
rejected_indices = np.where(y_pred == 1)[0]
print("Rejected test set indices:", rejected_indices)

# Let's choose the first rejected applicant or test index matching applicant characteristics
# (We can use test index 23 if it is predicted rejected, or any other appropriate rejected index)
idx_to_explain = 23 # using 23 as matched in expected report template
if y_pred[idx_to_explain] != 1:
    # If 23 is not rejected, use the first available rejected test applicant to show realistic pipeline
    idx_to_explain = rejected_indices[0]

selected_applicant_idx = idx_to_explain
applicant_features = X_test.iloc[selected_applicant_idx]
prob_bad = y_prob[selected_applicant_idx]


# Single explanation
# Let's compute individual SHAP values for this applicant
shap_val_single = shap_values_class1[selected_applicant_idx]
feature_names = X_test.columns.tolist()

# Sort features by highest impact towards positive class ('bad')
shap_local_df = pd.DataFrame({
    'feature': feature_names,
    'value': applicant_features.values,
    'shap_val': shap_val_single
}).sort_values(by='shap_val', ascending=False)

# Decode ordinal feature values back to readable raw strings for display
raw_features = df_raw.iloc[X_test.index[selected_applicant_idx]]

def decode_value(feature_name, val):
    # Helper to display original categorical value if applicable
    if feature_name in categorical_cols:
        orig_val = raw_features[feature_name]
        return f"{orig_val}"
    else:
        return f"{val}"

# --- LIME explanation ---
# Initialize LIME Tabular Explainer
lime_explainer = lime.lime_tabular.LimeTabularExplainer(
    training_data=np.array(X_train),
    feature_names=feature_names,
    class_names=['good', 'bad'],
    mode='classification',
    random_state=42
)

exp = lime_explainer.explain_instance(
    data_row=applicant_features,
    predict_fn=rf.predict_proba,
    num_features=5
)

lime_list = exp.as_list()

# Draw and display the SHAP local waterfall plot
plt.figure(figsize=(10, 4))
shap.plots.bar(shap.Explanation(values=shap_val_single, base_values=explainer.expected_value[1], data=applicant_features, feature_names=feature_names), max_display=5, show=False)
plt.title(f"SHAP Local Bar Plot (Applicant Test Index {selected_applicant_idx})", fontsize=12)
plt.tight_layout()
plt.savefig('shap_local.png')
plt.show()
plt.close()

print(f"Expected Output — Part B: Local Explanation of One Rejected Applicant")
print(f"Applicant (test index {selected_applicant_idx}) : P(bad) = {prob_bad:.2f}  ->  REJECTED\n")

print(f"SHAP (top 3)                  LIME (top 5)")
print("-"*62)

# Print SHAP top 3 side-by-side with LIME top 5
shap_top3 = shap_local_df.head(3).values
lime_top5 = lime_list

for k in range(5):
    # SHAP text
    if k < len(shap_top3):
        s_feat, s_val, s_sh = shap_top3[k]
        s_decoded = decode_value(s_feat, s_val)
        shap_text = f"{s_feat}={s_decoded:<10} {s_sh:+.2f}"
    else:
        shap_text = ""

    # LIME text
    l_cond, l_val = lime_top5[k]
    lime_text = f"{l_cond:<25} {l_val:+.2f}"

    print(f"{shap_text:<30} {lime_text}")

print("-"*62)

"""## TASK 6: Plain-language Rejection Message & Sensitive Attribute Review"""

# Sensitive attributes checklist
sensitive_attributes = ['age', 'status_and_sex', 'is_foreign_worker']
detected_sensitive = []

# Check if any sensitive attributes are in the top SHAP reasons
top_reasons = shap_local_df.head(3)['feature'].tolist()
for attr in sensitive_attributes:
    if attr in top_reasons:
        detected_sensitive.append(attr)

print("Sensitive attributes in reasons :", ", ".join(detected_sensitive) if detected_sensitive else "None", "-> REVIEW")

# Formulate message using non-sensitive reasons
# We identify non-sensitive top contributors from SHAP
non_sensitive_reasons = shap_local_df[~shap_local_df['feature'].isin(sensitive_attributes)].head(2)
rejection_reasons_str = []
for idx, row in non_sensitive_reasons.iterrows():
    feat = row['feature']
    val = decode_value(feat, row['value'])
    if feat == 'status_account':
        rejection_reasons_str.append("your current checking account balance is low or negative")
    elif feat == 'month_duration':
        rejection_reasons_str.append(f"the requested loan duration is long ({int(row['value'])} months)")
    elif feat == 'credit_amount':
        rejection_reasons_str.append(f"the requested credit amount ({int(row['value'])} DM) is high")
    else:
        rejection_reasons_str.append(f"{feat} is {val}")

message = f'"Your EMI request was not approved mainly because {rejection_reasons_str[0]} and {rejection_reasons_str[1]}."'
print(f"Message (legitimate reasons only): {message}")

