"""## TASK 1 & 2"""

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OrdinalEncoder
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, roc_auc_score
import pandas as pd
import numpy as np

# 1. Prepare Target Variable
df = df_raw.copy()
df['target'] = df['target'].map({'bad': 1, 'good': 0})

# Separate features (exactly 20 attributes) and target
X = df.drop(columns=['target'])
y = df['target']

print(f"Number of input attributes being used: {X.shape[1]}")
print("Attributes list:", X.columns.tolist())

# Identify categorical and numerical columns
categorical_cols = X.select_dtypes(include=['object', 'category']).columns.tolist()

# 2. Ordinal Encoding for categorical features as instructed
encoder = OrdinalEncoder(handle_unknown='use_encoded_value', unknown_value=-1)
X[categorical_cols] = encoder.fit_transform(X[categorical_cols].astype(str))

# 3. Stratified 80:20 Train-Test Split
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42
)

# 4. Train Random Forest (200 trees, max_depth = 8)
rf = RandomForestClassifier(n_estimators=200, max_depth=8, random_state=42)
rf.fit(X_train, y_train)

# 5. Model Evaluation
y_pred = rf.predict(X_test)
y_prob = rf.predict_proba(X_test)[:, 1]

accuracy = accuracy_score(y_test, y_pred)
roc_auc = roc_auc_score(y_test, y_prob)

print(f"Model : RandomForest (200 trees, depth 8)")
print(f"Test accuracy : {accuracy:.2f}      ROC-AUC : {roc_auc:.2f}")

"""## TASK 3: SHAP Global Importance"""

import shap
import lime
import lime.lime_tabular
import matplotlib.pyplot as plt

# --- TASK 3: SHAP Global Importance ---
# Compute SHAP values
explainer = shap.TreeExplainer(rf)
shap_values = explainer.shap_values(X_test)

# Note: shap_values is a list for classification [class_0, class_1] or a 3D array depending on version.
# Let's extract values for class = 1 (bad)
if isinstance(shap_values, list):
    shap_values_class1 = shap_values[1]
else:
    # For newer shap versions, shap_values may have shape (N, D, 2) or (N, D)
    if len(shap_values.shape) == 3:
        shap_values_class1 = shap_values[:, :, 1]
    else:
        shap_values_class1 = shap_values

# Save SHAP Summary Plot
plt.figure(figsize=(10, 6))
shap.summary_plot(shap_values_class1, X_test, show=False)
plt.title("SHAP Summary Plot (Class: bad)", fontsize=14)
plt.tight_layout()
plt.savefig('shap_summary.png')
plt.show()
plt.close()

# Get top 5 features by mean absolute SHAP value
mean_shap = np.abs(shap_values_class1).mean(axis=0)
importance_df = pd.DataFrame({
    'FEATURE': X_test.columns,
    'MEAN|SHAP|': mean_shap
}).sort_values(by='MEAN|SHAP|', ascending=False)

